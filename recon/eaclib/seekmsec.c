int seekmsecs(int fromsector, int tosector)
{
    int from;
    int to;

    from = fromsector / 19531;
    to = tosector / 19531;
    if (blackdevstation)
        return blackseekmsecstbl[from * 16 + to];
    return seekmsecstbl[from * 16 + to];
}

int returnseekmsecs(int fromsector, int tosector)
{
    int from;
    int to;

    from = fromsector / 19531;
    to = tosector / 19531;
    if (blackdevstation)
        return blackseekmsecstbl[from * 16 + to] + blackseekmsecstbl[to * 16 + from];
    return seekmsecstbl[from * 16 + to] + seekmsecstbl[to * 16 + from];
}
